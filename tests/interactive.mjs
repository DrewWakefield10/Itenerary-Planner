import {chromium,expect} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try {
await page.goto('http://127.0.0.1:5173/planner?destinations=baguio&days=3');
await expect(page.getByLabel('Number of days')).toHaveValue('3');
for(let i=0;i<5;i++)await page.getByRole('button',{name:'Next chapter'}).click();
await page.getByRole('button',{name:'Generate demo itinerary'}).click();
await expect(page.getByRole('heading',{name:'Baguio — my island story'})).toBeVisible();
await page.getByRole('button',{name:'Day 2 Baguio'}).click();
await page.getByRole('button',{name:'Lock Baguio Cathedral area',exact:true}).click();
await expect(page.getByRole('button',{name:'Edit Baguio Cathedral area',exact:true})).toBeDisabled();
await page.getByRole('button',{name:'Regenerate day',exact:true}).click();
await expect(page.getByRole('button',{name:'Unlock Baguio Cathedral area',exact:true})).toBeVisible();
await page.getByRole('button',{name:'Add activity',exact:true}).click();
await page.getByLabel('Activity name',{exact:true}).fill('My test detour');
await page.getByLabel('Estimated cost for whole group').fill('350');
await page.getByRole('button',{name:'Save activity',exact:true}).click();
await expect(page.getByRole('heading',{name:'My test detour'})).toBeVisible();
await page.getByRole('button',{name:'Edit My test detour',exact:true}).click();
await page.getByLabel('Start time',{exact:true}).fill('18:00');
await page.getByRole('button',{name:'Save activity',exact:true}).click();
await page.getByRole('button',{name:'Remove My test detour',exact:true}).click();
await expect(page.getByRole('heading',{name:'My test detour'})).toHaveCount(0);
await page.getByRole('button',{name:'Undo',exact:true}).click();
await expect(page.getByRole('heading',{name:'My test detour'})).toBeVisible();
await page.getByRole('button',{name:'Move My test detour up',exact:true}).click();
await page.getByRole('button',{name:'Make a Plan B',exact:true}).click();
await page.getByRole('button',{name:'Preview alternative',exact:true}).click();
const proposalOriginal=await page.evaluate(()=>localStorage.getItem('lakbay:trips'));
await expect(page.getByRole('button',{name:'Confirm & apply'})).toBeVisible();
assert.equal(proposalOriginal,await page.evaluate(()=>localStorage.getItem('lakbay:trips')));
await page.getByRole('button',{name:'Keep original'}).click();
await page.getByRole('tab',{name:'Map',exact:true}).click();
await expect(page.locator('.leaflet-marker-icon').first()).toBeVisible({timeout:10000});
await page.locator('.leaflet-marker-icon').first().click();
await expect(page.locator('.activity-card.selected')).toBeVisible();
await page.getByRole('tab',{name:'Budget',exact:true}).click();
await page.getByLabel('Actual Food',{exact:true}).fill('1234');
await expect(page.getByLabel('Actual Food',{exact:true})).toHaveValue('1234');
await page.getByRole('tab',{name:'Essentials',exact:true}).click();
await page.getByRole('checkbox',{name:'Identification and required documents'}).check();
await page.getByLabel('New checklist item').fill('Test packing item');
await page.getByRole('button',{name:'Add',exact:true}).click();
await expect(page.getByRole('checkbox',{name:'Test packing item'})).toBeVisible();
await page.getByLabel('Personal journal notes').fill('My journey note');
await page.getByRole('button',{name:'Save journal notes'}).click();
await page.reload();
await page.getByRole('tab',{name:'Essentials',exact:true}).click();
await expect(page.getByLabel('Personal journal notes')).toHaveValue('My journey note');
await expect(page.getByRole('checkbox',{name:'Identification and required documents'})).toBeChecked();
await page.getByRole('tab',{name:'Itinerary',exact:true}).click();
await page.screenshot({path:'tests/itinerary-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'tests/itinerary-mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.deepEqual(errors,[]);
console.log('Interactive browser: edit/add/remove/undo/reorder/locks, map sync, Plan B preview, budget, checklist, notes, reload, mobile overflow passed.');
}finally{await browser.close();}

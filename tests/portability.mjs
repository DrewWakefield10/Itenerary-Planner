import {chromium,expect} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
await page.goto('http://127.0.0.1:5173/planner?destinations=el-nido&days=5');
await expect(page.getByLabel('Number of days')).toHaveValue('5');
for(let i=0;i<5;i++)await page.getByRole('button',{name:'Next chapter'}).click();
await page.getByRole('button',{name:'Generate demo itinerary'}).click();
await expect(page.getByRole('heading',{name:'El Nido — my island story'})).toBeVisible();
const savedURL=page.url();
const downloadEvent=page.waitForEvent('download');
await page.getByRole('button',{name:'Export backup',exact:true}).click();
const download=await downloadEvent;const backup=await download.path();
await page.getByRole('button',{name:'Share snapshot',exact:true}).click();
const share=await page.getByLabel('Read-only trip link').inputValue();
await page.goto(share);
await expect(page.getByText('Read-only shared snapshot',{exact:true})).toBeVisible();
await expect(page.getByRole('button',{name:'Add activity',exact:true})).toHaveCount(0);
await page.emulateMedia({media:'print'});
await expect(page.getByText('Complete travel journal',{exact:true})).toBeVisible();
await page.pdf({path:'tests/trip-export.pdf',format:'A4',printBackground:true});
await page.emulateMedia({media:'screen'});
await page.goto('http://127.0.0.1:5173/my-trips');
await expect(page.locator('.postcard')).toHaveCount(1);
await page.getByLabel('Restore a Lakbay JSON backup').setInputFiles(backup);
await expect(page.getByText('Backup restored as a new trip.')).toBeVisible();
await expect(page.locator('.postcard')).toHaveCount(2);
await page.goto(savedURL);
await page.getByRole('button',{name:'Day 2 El Nido'}).click();
await page.getByRole('button',{name:'Make a Plan B',exact:true}).click();
await page.getByLabel('What changed?').selectOption('Heavy rain');
await page.getByRole('button',{name:'Preview alternative',exact:true}).click();
const old=await page.evaluate(()=>localStorage.getItem('lakbay:trips'));
await expect(page.getByRole('button',{name:'Confirm & apply'})).toBeEnabled();
assert.equal(old,await page.evaluate(()=>localStorage.getItem('lakbay:trips')));
await page.getByRole('button',{name:'Confirm & apply'}).click();
await expect(page.getByRole('heading',{name:'Flexible rest at your accommodation',exact:true}).first()).toBeVisible();
await page.getByRole('button',{name:'Undo',exact:true}).click();
await expect(page.getByRole('heading',{name:'Flexible rest at your accommodation',exact:true})).toHaveCount(0);
const bad=await page.request.post('http://127.0.0.1:5173/api/generate',{data:{request:{}}});assert.equal(bad.status(),400);
const weather=await page.request.get('http://127.0.0.1:5173/api/weather?destination=palawan&date=2030-01-01');assert.equal((await weather.json()).available,false);
assert.deepEqual(errors,[]);
console.log('Portability: JSON export/import, read-only sharing, complete print/PDF, Plan B confirmation/undo, invalid API and weather fallback passed.');
}finally{await browser.close();}
